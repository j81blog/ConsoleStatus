function Invoke-ConsoleStep {
    <#
        .SYNOPSIS
            Runs a scriptblock as a single console item and passes its output through.

        .DESCRIPTION
            Writes the item line, runs the action, and closes the line with OK or FAIL. Only the
            decoration goes to the console: whatever the action writes to the success stream is
            returned unchanged, so it can be assigned to a variable.

            Call Write-ConsoleTick from inside the action to advance the progress field, and
            Set-ConsoleStepDetail to report a value that is only known once the work has run.

        .PARAMETER Label
            What the step is, passed through to Write-ConsoleItem.

        .PARAMETER Value
            The thing being acted on, passed through to Write-ConsoleItem.

        .PARAMETER Action
            The work. Its success stream output is returned unchanged, so it can be assigned. It
            may call Write-ConsoleTick, Set-ConsoleStepDetail and Set-ConsoleStepNote.

        .PARAMETER TotalSteps
            Total units of work, passed through to Write-ConsoleItem so the bar is proportional.

        .PARAMETER ShowDuration
            Print the elapsed time for this step, whatever the ShowDuration setting says.

        .PARAMETER ContinueOnError
            Report FAIL and keep going instead of rethrowing the exception. The failure is in the
            log and in the summary either way.

        .EXAMPLE
            $files = Invoke-ConsoleStep -Label 'Enumerate' -Value 'C:\Temp' -Action { Get-ChildItem -Path 'C:\Temp' }
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Label,

        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [AllowEmptyString()]
        [string]$Value,

        [Parameter(Mandatory = $true)]
        [ValidateNotNull()]
        [scriptblock]$Action,

        [Parameter(Mandatory = $false)]
        [ValidateRange(0, [int]::MaxValue)]
        [int]$TotalSteps = 0,

        [Parameter(Mandatory = $false)]
        [switch]$ShowDuration,

        [Parameter(Mandatory = $false)]
        [switch]$ContinueOnError
    )

    $resultParams = @{}

    if ($PSBoundParameters.ContainsKey('ShowDuration')) {
        $resultParams.ShowDuration = $ShowDuration
    }

    Write-ConsoleItem -Label $Label -Value $Value -TotalSteps $TotalSteps

    try {
        $output = & $Action
        Write-ConsoleResult -Status OK @resultParams
        return $output
    } catch {
        Write-ConsoleResult -Status FAIL -ErrorRecord $_ @resultParams

        if (-not $ContinueOnError) {
            throw
        }

        Write-Verbose -Message "Step '$Label' failed: $($_.Exception.Message)"
    }
}

