function Write-ConsoleItem {
    <#
        .SYNOPSIS
            Starts an item line: writes the label and value and reserves the progress field.

        .DESCRIPTION
            Leaves the cursor on the same line and starts the step timer. Follow up with
            Write-ConsoleTick calls and close the line with Write-ConsoleResult.

        .PARAMETER Label
            What the item is. Truncated to the label column in Column mode.

        .PARAMETER Value
            The thing being acted on: a version, a path, a host name. Truncated to the value column
            in Column mode, left at its natural length in Flow mode.

        .PARAMETER TotalSteps
            Total units of work for this item. Ticks are then drawn proportionally, so the bar
            spans the field exactly. Leave at 0 when the total is unknown.

        .EXAMPLE
            Write-ConsoleItem -Label 'Execution policy' -Value (Get-ExecutionPolicy).ToString()

        .EXAMPLE
            Write-ConsoleItem -Label 'Process queue' -Value '200 items' -TotalSteps 200
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $true)]
        [ValidateNotNullOrEmpty()]
        [string]$Label,

        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [AllowEmptyString()]
        [string]$Value,

        [Parameter(Mandatory = $false)]
        [ValidateRange(0, [int]::MaxValue)]
        [int]$TotalSteps = 0
    )

    $cfg = $script:ConsoleStatus
    $cfg.Ticks = 0
    $cfg.Detail = ''
    $cfg.Note = @()
    $cfg.TotalSteps = $TotalSteps
    $cfg.DoneSteps = 0
    $cfg.BarLines = 1
    $cfg.Overflowed = $false
    $cfg.ItemOpen = $true
    $cfg.Stopwatch = [System.Diagnostics.Stopwatch]::StartNew()

    $Label = Format-SingleLine -Text $Label
    $Value = Format-SingleLine -Text $Value

    $cfg.CurrentLabel = $Label
    $cfg.CurrentValue = $Value

    Write-HostText -Text (' ' * $cfg.Indent) -NoNewline

    if ($cfg.Mode -eq 'Column') {
        # -1 keeps a gap between fields. ValueWidth 0 drops the value column.
        Write-HostText -Text (Format-FixedWidth -Text $Label -Width ($cfg.LabelWidth - 1)) -NoNewline -Color 'Gray'
        Write-HostText -Text ' ' -NoNewline

        if ($cfg.ValueWidth -gt 0) {
            Write-HostText -Text (Format-FixedWidth -Text $Value -Width ($cfg.ValueWidth - 1)) -NoNewline -Color 'White'
            Write-HostText -Text ' ' -NoNewline
        }

        # The trailing -1 is the status gap.
        $cfg.FieldWidth = $cfg.LineWidth - $cfg.Indent - $cfg.LabelWidth - $cfg.ValueWidth - $cfg.StatusWidth - 1
        $cfg.FieldStart = $cfg.LineWidth - $cfg.StatusWidth - 1 - $cfg.FieldWidth
        return
    }
    $maxText = $cfg.LineWidth - $cfg.Indent - $cfg.StatusWidth - 6
    $text = $Label

    if (-not [string]::IsNullOrEmpty($Value)) {
        $text = "$Label $Value"
    }

    if ($text.Length -gt $maxText) {
        # Same truncation as the column mode, which also survives a line too narrow for the dots.
        $text = Format-FixedWidth -Text $text -Width $maxText
        $Label = $text
        $Value = ''
    }

    Write-HostText -Text $Label -NoNewline -Color 'Gray'

    if (-not [string]::IsNullOrEmpty($Value)) {
        Write-HostText -Text " $Value" -NoNewline -Color 'White'
    }

    Write-HostText -Text ' ' -NoNewline
    $cfg.FieldWidth = $cfg.LineWidth - $cfg.Indent - $text.Length - 1 - $cfg.StatusWidth - 1
    $cfg.FieldStart = $cfg.LineWidth - $cfg.StatusWidth - 1 - $cfg.FieldWidth
}

