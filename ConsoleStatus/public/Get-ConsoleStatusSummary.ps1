function Get-ConsoleStatusSummary {
    <#
        .SYNOPSIS
            Returns the counts per status plus the two timings.

        .DESCRIPTION
            Covers everything recorded since the last Reset-ConsoleStatusLog. Lines written with
            NoRecord, which includes the summary block itself, are not counted.

            DurationMs is the time spent inside the steps, added up. ElapsedMs is the wall clock
            for the whole run, so it also covers everything between the steps.

        .EXAMPLE
            exit (Get-ConsoleStatusSummary).Fail
    #>
    [CmdletBinding()]
    [OutputType([PSCustomObject])]
    param()

    $total = 0
    $script:ConsoleStatusTally.Values | ForEach-Object { $total += $_ }

    $elapsed = 0
    $script:ConsoleStatusLog | ForEach-Object { $elapsed += $_.DurationMs }

    return [PSCustomObject]@{
        Total      = $total
        OK         = $script:ConsoleStatusTally['OK']
        Warn       = $script:ConsoleStatusTally['WARN']
        Fail       = $script:ConsoleStatusTally['FAIL']
        Skip       = $script:ConsoleStatusTally['SKIP']
        DurationMs = $elapsed
        ElapsedMs  = [int]$script:ConsoleStatus.RunStopwatch.ElapsedMilliseconds
    }
}

