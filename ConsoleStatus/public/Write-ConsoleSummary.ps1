function Write-ConsoleSummary {
    <#
        .SYNOPSIS
            Writes a closing section with the totals.

        .DESCRIPTION
            The summary lines are rendered with NoRecord, so they do not appear in their own totals.
            Steps completed carries the time spent inside the steps, Total time the wall clock for
            the whole run. When anything failed, the failures are listed underneath with their
            reason.

        .PARAMETER Title
            Heading for the summary section. Defaults to 'Summary'.

        .EXAMPLE
            Write-ConsoleSummary
            exit (Get-ConsoleStatusSummary).Fail
    #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory = $false)]
        [ValidateNotNullOrEmpty()]
        [string]$Title = 'Summary'
    )

    $cfg = $script:ConsoleStatus
    $summary = Get-ConsoleStatusSummary

    Write-ConsoleSection -Title $Title

    Write-ConsoleItem -Label 'Steps completed' -Value $summary.Total
    Write-ConsoleResult -Status OK -Detail (Format-Duration -Milliseconds $summary.DurationMs) -NoRecord

    Write-ConsoleItem -Label 'Total time'
    Write-ConsoleResult -Status OK -Detail (Format-Duration -Milliseconds $summary.ElapsedMs) -NoRecord

    if ($summary.Warn -gt 0) {
        Write-ConsoleItem -Label 'Warnings' -Value $summary.Warn
        Write-ConsoleResult -Status WARN -Detail '' -NoRecord
    }

    if ($summary.Skip -gt 0) {
        Write-ConsoleItem -Label 'Skipped' -Value $summary.Skip
        Write-ConsoleResult -Status SKIP -Detail '' -NoRecord
    }

    Write-ConsoleItem -Label 'Failed' -Value $summary.Fail

    if ($summary.Fail -eq 0) {
        Write-ConsoleResult -Status OK -Detail '' -NoRecord
        return
    }

    Write-ConsoleResult -Status FAIL -Detail '' -NoRecord
    $indent = ' ' * ($cfg.Indent + 4)

    foreach ($failure in ($script:ConsoleStatusLog | Where-Object { $_.Status -eq 'FAIL' })) {
        $label = $failure.Label

        if (-not [string]::IsNullOrEmpty($failure.Value)) {
            $label = "$label ($($failure.Value))"
        }

        Write-ConsoleNoteBlock -Text $label -Color 'Red'

        $reason = if (-not [string]::IsNullOrEmpty($failure.Error)) { $failure.Error } else { $failure.Detail }

        foreach ($chunk in (Split-TextToWidth -Text $reason -Width ($cfg.LineWidth - $indent.Length))) {
            Write-HostText -Text "$indent$chunk" -Color 'Gray'
        }
    }
}

