function Get-ConsoleStatusPreference {
    <#
        .SYNOPSIS
            Returns the $ConsoleStatusPreference hashtable from the caller scope, or an empty one.

        .DESCRIPTION
            The lookup uses the caller session state, so the variable is found whether it was set
            inside the calling script, inside a function, in the profile or in the global scope.

        .PARAMETER CallerState
            Session state to search, normally $PSCmdlet.SessionState of the public function being
            called. When null, only the global scope is searched.
    #>
    [CmdletBinding()]
    [OutputType([Hashtable])]
    param(
        [Parameter(Mandatory = $false)]
        [AllowNull()]
        [System.Management.Automation.SessionState]$CallerState
    )

    $variable = $null

    if ($null -ne $CallerState) {
        $variable = $CallerState.PSVariable.Get('ConsoleStatusPreference')
    }

    if ($null -eq $variable) {
        $variable = Get-Variable -Name 'ConsoleStatusPreference' -Scope 'Global' -ErrorAction SilentlyContinue
    }

    if ($null -eq $variable -or $null -eq $variable.Value) {
        return @{}
    }

    if ($variable.Value -isnot [hashtable]) {
        throw "`$ConsoleStatusPreference must be a hashtable, got $($variable.Value.GetType().Name)."
    }

    return $variable.Value
}

