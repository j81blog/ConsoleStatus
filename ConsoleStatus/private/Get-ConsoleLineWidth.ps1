function Get-ConsoleLineWidth {
    <#
        .SYNOPSIS
            Returns the line width to render at.

        .DESCRIPTION
            Resolution order:

                1. Width setting, if not 0. The exact line width, no margin subtracted and no
                   MinWidth or MaxWidth clamping, but still validated against the real console.
                2. $env:CONSOLESTATUS_WIDTH, for scheduled tasks and build agents where the layout
                   has to be set from outside the script. Treated as a terminal width, so the
                   margin and the clamps apply.
                3. The detected console width.
                4. 80.

            One column is left free for measured widths so a full width line does not trigger an
            automatic line wrap.
    #>
    [CmdletBinding()]
    [OutputType([Int32])]
    param()

    $cfg = $script:ConsoleStatus
    $detected = Get-DetectedConsoleWidth

    # Pinned: exact, no margin and no clamp, but still validated against the console.
    if ($cfg.Width -gt 0) {
        return (Assert-ConsoleFit -Requested $cfg.Width -Detected $detected -Source 'Width')
    }

    $width = 0
    $fromEnvironment = $false

    if (-not [string]::IsNullOrWhiteSpace($env:CONSOLESTATUS_WIDTH)) {
        $parsed = 0

        if ([int]::TryParse($env:CONSOLESTATUS_WIDTH, [ref]$parsed) -and $parsed -gt 0) {
            $width = $parsed
            $fromEnvironment = $true
        } else {
            # Ambient value, not the script author's: warn and fall through rather than throw.
            Write-Warning -Message "Ignoring CONSOLESTATUS_WIDTH='$env:CONSOLESTATUS_WIDTH', expected a positive number."
        }
    }

    if ($width -lt 1) {
        $width = $detected
    }

    if ($width -lt 1) {
        $width = 80
    }

    $line = $width - 1

    if ($fromEnvironment) {
        $line = Assert-ConsoleFit -Requested $line -Detected $detected -Source 'CONSOLESTATUS_WIDTH'
    }

    if ($line -lt $cfg.MinWidth) {
        $line = $cfg.MinWidth
    }

    if ($line -gt $cfg.MaxWidth) {
        $line = $cfg.MaxWidth
    }

    return $line
}

