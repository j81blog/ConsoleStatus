function Get-DetectedConsoleWidth {
    <#
        .SYNOPSIS
            Returns the real console width, or 0 when it cannot be determined.

        .DESCRIPTION
            WindowSize is deliberately preferred over BufferSize. On legacy conhost the buffer can
            be wider than the window, which is what produces the horizontal scrollbar, and writing
            to the buffer width would push the status column off screen. BufferSize is only used
            for hosts that leave WindowSize empty.

            [Console]::WindowWidth is not used at all: it throws an IOException as soon as standard
            output is redirected, which covers every piped or logged run.
    #>
    [CmdletBinding()]
    [OutputType([Int32])]
    param()

    foreach ($property in @('WindowSize', 'BufferSize')) {
        try {
            $width = [int]$Host.UI.RawUI.$property.Width
        } catch {
            $width = 0
        }

        if ($width -gt 0) {
            return $width
        }
    }

    return 0
}

